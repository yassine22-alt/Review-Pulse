"""Generate the extraction contract docs from the code, the rule packs and the evaluation reports.

    python scripts/gen_docs.py          # write docs/extraction_schema.md, docs/extraction_catalogue.md,
                                        # schemas/*.schema.json
    python scripts/gen_docs.py --check  # exit 1 if any of them is out of date (run by the test suite)

Nothing in these files is typed by hand: field descriptions come from schema.py, the attrs contract
from ELEMENT_ATTRS, the rules each catalogue item feeds from the rule packs, and every measured number
from the report that produced it.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from reviewpulse import schema as S  # noqa: E402

MODELS = [S.Sheet, S.Primitive, S.TextItem, S.Scale, S.Dimension, S.Layout, S.BuildingModel, S.Element,
          S.Room, S.Edge, S.Finding, S.Prov]
EXPORTS = {"sheet": S.Sheet, "building": S.BuildingModel, "finding": S.Finding}


# ---------------------------------------------------------------- schema doc
def _type_name(ann) -> str:
    t = str(ann).replace("typing.", "").replace("reviewpulse.schema.", "")
    t = re.sub(r"<class '([\w.]+)'>", r"\1", t)
    return t.replace("NoneType", "None")


def _default(f) -> str:
    if f.is_required():
        return "required"
    if f.default_factory is not None:
        return repr(f.default_factory())
    return repr(f.default)


def _model_table(m) -> str:
    rows = ["| field | type | default | meaning |", "|---|---|---|---|"]
    for name, f in m.model_fields.items():
        typ = _type_name(f.annotation).replace("|", "\\|")
        rows.append(f"| `{name}` | `{typ}` | {_default(f).replace('|', '/')} | {f.description or ''} |")
    return "\n".join(rows)


def _attrs_table() -> str:
    seen, out = {}, []
    for cls, spec in S.ELEMENT_ATTRS.items():
        key = id(spec)
        if key in seen:
            out.append(f"**{cls}**: same keys as {seen[key]}.\n")
            continue
        seen[key] = f"`{cls}`"
        out.append(f"**{cls}**\n")
        out.append("| key | type | meaning |\n|---|---|---|")
        for k, (types, meaning) in spec.items():
            ts = " or ".join("None" if t is type(None) else t.__name__ for t in types)
            out.append(f"| `{k}` | {ts} | {meaning} |")
        out.append("")
    return "\n".join(out)


def _examples() -> dict:
    """Small objects covering geometry, confidence and provenance, validated against the models."""
    prov = {"source": "vector", "stage": "openings_v1", "confidence": 0.9, "evidence": {"arc": "s0:p41"}}
    door = S.Element(id="s0:door_3f2a", cls="door", geom=[(1200.0, 400.0), (2100.0, 400.0), (2100.0, 600.0),
                                                           (1200.0, 600.0)],
                     member_ids=["s0:p41", "s0:p42"], tag="D2",
                     attrs={"width_m": 0.9, "mid": (1650.0, 500.0), "normal": (0.0, 1.0), "thickness": 200.0,
                            "wall_id": "s0:wall_91c0", "hinge": (1200.0, 600.0), "radius": 900.0,
                            "swing_side": 1, "width_source": "arc_radius"},
                     prov=S.Prov(**prov))
    room = S.Room(id="s0:room_07", polygon=[(0, 0), (3600, 0), (3600, 3000), (0, 3000)], label="CHAMBRE 2",
                  type="bedroom", area_m2=10.8, min_width_m=3.0,
                  prov=S.Prov(source="derived", stage="rooms_v1", confidence=0.85))
    finding = S.Finding(rule_id="C-D3", verdict="WARNING", severity="major", subject_ids=["s0:room_07"],
                        message="Bedroom floor area 10.8 m2 is below 11 m2 (verify measurement: scale estimated)",
                        detected="10.80 m2", required=">= 11.00 m2", tier="T3",
                        source={"doc": "docs/requirements_example.md", "clause": "Art. 6.2"})
    model = S.BuildingModel(sheet=S.Sheet(id="s0", source_file="plan.pdf", mode="vector", coord_unit="paper_mm",
                                          width=420, height=297), elements=[door], rooms=[room])
    assert S.check_attrs(model) == [], S.check_attrs(model)
    for obj in (door, room, finding):
        # JSON has no tuples: attrs points come back as lists, so compare the serialised forms
        assert type(obj).model_validate_json(obj.model_dump_json()).model_dump_json() == obj.model_dump_json()
    return {"Element (door)": door, "Room": room, "Finding": finding}


def render_schema() -> str:
    parts = [
        "# Extraction schema",
        "",
        "> Generated by `python scripts/gen_docs.py` from `src/reviewpulse/schema.py`; do not edit by hand.",
        f"> Schema version {S.SCHEMA_VERSION}. JSON Schema files: `schemas/*.schema.json`.",
        "",
        "## The three files",
        "",
        "| file | model | written by | read by |",
        "|---|---|---|---|",
        "| `sheet_<n>.json` | `Sheet` | Reader: ingest + annotate (what was drawn) | Interpreter |",
        "| `building_<n>.json` | `BuildingModel` | Interpreter: perception (what it means) | Judge, reports, app |",
        "| `findings.json` | list of `Finding` | Judge: rules engine (what is wrong) | reports, app |",
        "",
        "## Conventions (the intermediate-representation decisions, task B3)",
        "",
        "1. **Coordinates.** Sheet space, y axis up, origin at the sheet's lower-left corner (D6).",
        "   Raster and PDF pages are mapped there by an affine transform at ingest.",
        "2. **Units.** Paper millimetres for PDF, SVG and raster sheets; drawing units for DXF",
        "   (`Sheet.coord_unit`). Real metres exist only through `Sheet.scale.metres_per_unit`, and every",
        "   metric value in the model (`width_m`, `area_m2`, ...) is derived from it. `None` means unknown and",
        "   metric rules are then NOT_EVALUATED, never guessed.",
        "3. **Scale provenance.** `Scale.method` says how it was found. Only `dxf_units`, `dimension_consensus`,",
        "   `user` and `scale_bar` count as verified; `symbol_prior` (door-size or wall-thickness prior) is an",
        "   estimate and caps metric verdicts at WARNING.",
        "4. **Uncertainty.** Three levels: `Prov.confidence` per value; `Element.confirmed` /",
        "   `attrs.needs_confirmation` per element; `BuildingModel.tier` per model (T1 exact vector with a",
        "   verified scale, T2 partly estimated, T3 estimated). A FAIL needs T1 or confirmed deciding elements;",
        "   otherwise the verdict is WARNING with the reason (engine/policy.py).",
        "5. **Provenance.** Every primitive, text, dimension, element, room and edge carries `Prov`: input kind,",
        "   producing stage and version, confidence and stage evidence. Elements list the primitives they were",
        "   built from (`member_ids`), so every finding can be traced back to drawn marks.",
        "6. **Versioning.** Files carry `schema_version`; loaders refuse an unknown major version.",
        "",
        "## Models",
        "",
    ]
    for m in MODELS:
        parts += [f"### {m.__name__}", "", (m.__doc__ or "").strip(), "", _model_table(m), ""]
    parts += ["## Element attributes (`Element.attrs`)", "",
              "Checked on pipeline output by `schema.check_attrs` (tests/golden/test_contract.py): an unknown",
              "key or a wrong value type fails the build.", "", _attrs_table(),
              "## Validated examples", "",
              "These objects are built and validated by the generator (round-trip and attrs contract).", ""]
    for name, obj in _examples().items():
        parts += [f"**{name}**", "", "```json", obj.model_dump_json(indent=1, exclude_defaults=True), "```", ""]
    return "\n".join(parts).rstrip() + "\n"


# ---------------------------------------------------------------- catalogue
def _metric(report: str, key: str) -> str:
    text = (ROOT / report).read_text(encoding="utf-8")
    m = re.search(r"## Metrics\s+```\n(.*?)```", text, re.S)
    if not m:
        raise SystemExit(f"{report}: no metrics block")
    node = yaml.safe_load(m.group(1))
    for k in key.split("."):
        if not isinstance(node, dict) or k not in node:
            raise SystemExit(f"{report}: metric {key!r} not found")
        node = node[k]
    return f"{node:.3f}" if isinstance(node, float) else str(node)


def _rules():
    from reviewpulse.cli import DEFAULT_PACK
    from reviewpulse.rules.schema import load_pack

    return [r for r in load_pack(DEFAULT_PACK) if r.status == "approved"]


def render_catalogue() -> str:
    cat = yaml.safe_load((ROOT / "docs" / "catalogue.yaml").read_text(encoding="utf-8"))
    rules = _rules()
    counts: dict[str, int] = {}
    parts = ["# Extraction catalogue", "",
             "> Generated by `python scripts/gen_docs.py` from `docs/catalogue.yaml`, the starter rule pack and",
             "> the evaluation reports; do not edit by hand. Rules per item are derived from each rule's `needs`",
             "> and check function; every number is read from the report cited.", "",
             "Priority: **P0** an approved rule cannot run without it; **P1** improves accuracy or makes more",
             "rules runnable; **P2** later.", ""]
    for gid, gname in cat["groups"].items():
        items = [i for i in cat["items"] if i["group"] == gid]
        parts += [f"## {gname}", "", "| id | item | priority | status | produced by | in the schema | rules fed |",
                  "|---|---|---|---|---|---|---|"]
        for it in items:
            fed = sorted({r.id for r in rules if set(r.needs) & set(it["needs"]) or r.check.fn in it["fns"]})
            counts[it["priority"]] = counts.get(it["priority"], 0) + 1
            parts.append(f"| {it['id']} | {it['name']} | {it['priority']} | {it['status']} | "
                         f"{it['produced_by']} | `{it['schema']}` | {', '.join(fed) or '-'} |")
        parts.append("")
        meas = [(it["id"], m) for it in items for m in it.get("measured", [])]
        if meas:
            parts += ["Measured:", ""]
            for iid, m in meas:
                if not (ROOT / m["report"]).exists():
                    raise SystemExit(f"{iid}: report {m['report']} does not exist")
                v = _metric(m["report"], m["key"]) if "key" in m else m["value"]
                parts.append(f"- {iid}, {m['label']}: **{v}** ([report](../{m['report']}))")
            parts.append("")
    uncovered = sorted({r.id for r in rules} - {r.id for it in cat["items"] for r in rules
                                                if set(r.needs) & set(it["needs"]) or r.check.fn in it["fns"]})
    parts += ["## Coverage", "",
              f"{len(cat['items'])} items: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + ".",
              f"Approved rules: {len(rules)}; rules no catalogue item feeds: {', '.join(uncovered) or 'none'}.", ""]
    return "\n".join(parts).rstrip() + "\n"


# ---------------------------------------------------------------- main
def outputs() -> dict[Path, str]:
    out = {ROOT / "docs" / "extraction_schema.md": render_schema(),
           ROOT / "docs" / "extraction_catalogue.md": render_catalogue()}
    for name, m in EXPORTS.items():
        out[ROOT / "schemas" / f"{name}.schema.json"] = json.dumps(m.model_json_schema(), indent=1) + "\n"
    return out


def main(check: bool) -> int:
    stale = []
    for path, text in outputs().items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if check and stale:
        print("out of date (run python scripts/gen_docs.py):", ", ".join(stale))
        return 1
    print("up to date" if check else "written: " + (", ".join(stale) or "nothing changed"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main("--check" in sys.argv))
