"""Mine (room label text, room type) pairs from CubiCasa5K ground truth.

    python scripts/mine_room_labels.py            # train + val -> lexicon; test pairs kept for eval

Each CubiCasa ``Space <Type> ...`` group holds the label drawn on the plan (``TextLabel NameLabel``).
Writes
  data/mappings/cubicasa_room_labels.json   every (split, label, space class) with counts
  src/reviewpulse/annotate/lexicon/mined_cubicasa.yaml
      labels seen >= MIN_COUNT times in train+val whose room type is >= MIN_PURITY pure.
The test split is never used to build the lexicon.
"""

from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

MIN_COUNT = 5
MIN_PURITY = 0.8


def pairs_of(folder: str) -> list[tuple[str, str]]:
    from lxml import etree

    try:
        root = etree.parse(str(Path(folder) / "model.svg")).getroot()
    except (OSError, etree.XMLSyntaxError):
        return []
    out = []
    for el in root.iter():
        if not isinstance(el.tag, str):
            continue
        cls = (el.get("class") or "").strip()
        if cls != "Space" and not cls.startswith("Space "):
            continue
        for lab in el.iter():
            if isinstance(lab.tag, str) and "NameLabel" in (lab.get("class") or ""):
                txt = " ".join(t.strip() for t in lab.itertext() if t.strip())
                if txt:
                    out.append((txt, cls[len("Space"):].strip()))
                break
    return out


def main() -> None:
    from reviewpulse.annotate.text_classify import label_core
    from reviewpulse.eval.adapters.cubicasa import room_type_of, split_ids

    data = ROOT / "data"
    rows = []
    with ProcessPoolExecutor(max_workers=8) as ex:
        for split in ("train", "val", "test"):
            folders = [str(p) for p in split_ids(data, split)]
            for prs in ex.map(pairs_of, folders, chunksize=16):
                rows += [(split, t, c) for t, c in prs]
    counts = Counter(rows)
    out = data / "mappings" / "cubicasa_room_labels.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps([{"split": s, "label": t, "space_class": c, "n": n}
                               for (s, t, c), n in counts.most_common()], ensure_ascii=False, indent=0),
                   encoding="utf-8")
    by_core: dict[str, Counter] = defaultdict(Counter)
    for (s, t, c), n in counts.items():
        if s == "test":
            continue
        rt = room_type_of(c)
        core = label_core(t)
        if core and rt != "other":
            by_core[core][rt] += n
    mined: dict[str, list[str]] = defaultdict(list)
    for core, ctr in sorted(by_core.items()):
        rt, n = ctr.most_common(1)[0]
        tot = sum(ctr.values())
        if tot >= MIN_COUNT and n / tot >= MIN_PURITY:
            mined[rt].append(core)
    lex = ROOT / "src" / "reviewpulse" / "annotate" / "lexicon" / "mined_cubicasa.yaml"
    lines = ["# GENERATED by scripts/mine_room_labels.py from CubiCasa5K train+val ground truth",
             f"# (label seen >= {MIN_COUNT} times, room type >= {MIN_PURITY:.0%} pure). Data: CC BY-NC 4.0.",
             "source: cubicasa5k-train-val", "types:"]
    for rt in sorted(mined):
        lines.append(f"  {rt}: [{', '.join(json.dumps(w, ensure_ascii=False) for w in sorted(mined[rt]))}]")
    lex.write_text("\n".join(lines) + "\n", encoding="utf-8")
    n_split = Counter(s for (s, _t, _c) in rows)
    print(f"pairs per split {dict(n_split)}; distinct cores {len(by_core)}; mined "
          f"{sum(len(v) for v in mined.values())} -> {lex}")
    cls_counts = Counter(c for (_s, _t, c) in rows)
    print("space classes:", cls_counts.most_common(60))


if __name__ == "__main__":
    main()
